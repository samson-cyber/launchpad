#!/usr/bin/env node
// ===========================================================================
// [DP6] TAG COLOURS - a tag no goal made gets the least-used palette colour;
// a tag a goal made keeps the goal rotation exactly as it was.
//
// WHY THIS EXISTS. createTag used to default every colourless tag to
// nextAutoTagColor, whose counter only goal-made tags advance. With no goals,
// four #tags typed in quick add came out four identical blues, and Insights'
// Time by tag share bar - one bar split by tag colour - showed no parts. The
// 2.1.0 store screenshot's tag ring had the same single colour, and nobody saw
// it for two months, which is the argument for a gate rather than a note.
//
// WHAT IT HOLDS, against the real storage.js in a VM with a fake
// chrome.storage:
//   - colourless manual tags walk the palette in order while colours are free
//   - a colour already on a LIVE tag is skipped, compared case-insensitively
//   - a TRASHED tag's colour is free again
//   - once all eight are used, reuse stays even (least-used, palette order)
//   - an explicit colour always wins
//   - the pickers' default (nextManualTagColor) is what createTag then picks
//   - the GOAL rotation is untouched: manual tags never advance it, trashed
//     goal tags still count (DECISIONS [1.0.9.1]), and createTag called with
//     autoGeneratedFromGoalId still takes it
//
// Exit codes: 0 pass · 1 failures · 2 the subject did not load, or the gate
// produced too few rows. `--mutate` re-runs the suite against seeded
// reversions, each of which must turn it red. `--boot-check` is what
// check-mutation-boot runs.
// ===========================================================================
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const args = process.argv.slice(2);
const MUTATE = args.includes("--mutate");
const repoRoot = args.find((a) => !a.startsWith("--")) || path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SUBJECT = "storage.js";

// M4/M7: the working copy is CRLF and the blob LF. Normalise before any seed
// anchor is matched.
function readSubject() {
  return fs.readFileSync(path.join(repoRoot, SUBJECT), "utf8").replace(/\r\n/g, "\n");
}

const PALETTE = ["#4A90E2", "#7ED321", "#F5A623", "#D0021B", "#9013FE", "#50E3C2", "#F8E71C", "#BD10E0"];

function fixture(tags) {
  return {
    workspaces: [{
      id: "main", name: "Main", createdAt: 1, isReadOnly: false,
      groupOrder: ["ungrouped"],
      groups: [{ id: "ungrouped", name: "Ungrouped", shortcuts: [], deletedAt: null }],
      goals: [], tasks: [], tags: tags || [], namedSessions: [], notes: [], notebooks: [],
      tracking: { enabled: true }
    }],
    workspaceOrder: ["main"], activeWorkspaceId: "main", trackingPaused: false,
    settings: { columns: 6, collapsedGroups: {}, combinedAnalyticsEnabled: false, endOfDayMinutes: 1020 },
    pro: { subscriptionStatus: "free", licenseKey: null, instanceId: null, instanceName: null,
           email: null, trialStartedAt: null, trialEndedAt: null, lastVerifiedAt: null }
  };
}
const tag = (name, color, extra) => ({ id: "t-" + name, name, color, autoGeneratedFromGoalId: null, createdAt: 1, deletedAt: null, ...(extra || {}) });

function boot(src) {
  const store = { data: fixture() };
  const chrome = {
    runtime: { getManifest: () => ({ version: "2.2.0" }), lastError: null, id: "t" },
    storage: {
      local: {
        QUOTA_BYTES: 10485760,
        get: async (k) => {
          const out = {};
          const keys = k === null ? Object.keys(store) : (Array.isArray(k) ? k : [k]);
          for (const key of keys) if (key in store) out[key] = JSON.parse(JSON.stringify(store[key]));
          return out;
        },
        set: async (obj) => { for (const [k, v] of Object.entries(obj)) store[k] = JSON.parse(JSON.stringify(v)); },
        remove: async () => {},
        getBytesInUse: async () => JSON.stringify(store).length
      }
    }
  };
  const sandbox = {
    chrome, crypto, Date, JSON, Math, Object, Array, Set, Map, String,
    Number, Boolean, isFinite, setTimeout, structuredClone, Promise, Error, RegExp,
    parseInt, parseFloat, Intl, Proxy, Reflect,
    I18n: { t: (k) => k, th: (k) => k },
    ProAccess: { getProAccessLevel: () => "active", isProAccessibleLevel: () => true },
    console: { log() {}, warn() {}, error() {} }
  };
  sandbox.globalThis = sandbox;
  vm.createContext(sandbox);
  vm.runInContext(src, sandbox, { filename: SUBJECT });
  const S = sandbox.Storage;
  if (!S || typeof S.createTag !== "function" || typeof S.createGoal !== "function") {
    throw new Error("Storage.createTag / createGoal missing after load");
  }
  return { S };
}

async function suite(src) {
  const rows = [];
  const chk = (name, ok, extra = "") => rows.push({ name, ok: !!ok, extra });
  const eq = (name, got, want) => chk(name, JSON.stringify(got) === JSON.stringify(want), `got ${JSON.stringify(got)} want ${JSON.stringify(want)}`);
  const ws0 = (d) => d.workspaces[0];

  // The constant this gate assumes is the constant that ships.
  { const { S } = boot(src); eq("TAG_PALETTE is the eight-colour palette this gate is written against", S.TAG_PALETTE, PALETTE); }

  // 1. A fresh workspace, colourless manual tags: the palette in order.
  {
    const { S } = boot(src); const d = fixture();
    const got = [];
    for (const n of ["deep work", "writing", "admin", "review"]) got.push((await S.createTag(d, { name: n })).color);
    eq("four colourless manual tags take the first four palette colours, in order", got, PALETTE.slice(0, 4));
    eq("no two of them share a colour", new Set(got).size, 4);
  }
  // 2. Ten colourless tags: all eight used once, then reuse starts at the front.
  {
    const { S } = boot(src); const d = fixture();
    const got = [];
    for (let i = 0; i < 10; i++) got.push((await S.createTag(d, { name: "t" + i })).color);
    eq("tags 1-8 use every palette colour once", got.slice(0, 8), PALETTE);
    eq("tags 9 and 10 reuse the palette from the front", got.slice(8), PALETTE.slice(0, 2));
  }
  // 3. Colours already on live tags are skipped.
  {
    const { S } = boot(src); const d = fixture([tag("a", PALETTE[0]), tag("b", PALETTE[1])]);
    eq("a manual tag skips colours live tags already use", (await S.createTag(d, { name: "c" })).color, PALETTE[2]);
  }
  // 4. Case-insensitive: a lower-case hex is the same colour.
  {
    const { S } = boot(src); const d = fixture([tag("a", PALETTE[0].toLowerCase())]);
    eq("a lower-case copy of a palette colour counts as that colour", (await S.createTag(d, { name: "c" })).color, PALETTE[1]);
  }
  // 5. A trashed tag's colour is free again.
  {
    const { S } = boot(src); const d = fixture([tag("gone", PALETTE[0], { deletedAt: 5 }), tag("b", PALETTE[1])]);
    eq("a trashed tag's colour is available to a new manual tag", (await S.createTag(d, { name: "c" })).color, PALETTE[0]);
  }
  // 6. Least-used once everything is taken.
  {
    const { S } = boot(src);
    const many = PALETTE.map((c, i) => tag("p" + i, c)).concat([tag("x", PALETTE[0]), tag("y", PALETTE[2])]);
    const d = fixture(many);
    eq("with every colour used, the least-used one comes next (palette order breaks the tie)", (await S.createTag(d, { name: "z" })).color, PALETTE[1]);
  }
  // 7. A colour outside the palette uses no palette slot.
  {
    const { S } = boot(src); const d = fixture([tag("odd", "#123456")]);
    eq("a non-palette colour does not take a palette slot", (await S.createTag(d, { name: "c" })).color, PALETTE[0]);
  }
  // 8. An explicit colour always wins.
  {
    const { S } = boot(src); const d = fixture();
    eq("an explicit colour is stored as given", (await S.createTag(d, { name: "c", color: "#123456" })).color, "#123456");
    eq("an invalid explicit colour is refused", await S.createTag(d, { name: "d", color: "blue" }), null);
  }
  // 9. The pickers pre-select what createTag will then pick.
  {
    const { S } = boot(src); const d = fixture([tag("a", PALETTE[0]), tag("b", PALETTE[2])]);
    const predicted = typeof S.nextManualTagColor === "function" ? S.nextManualTagColor(ws0(d)) : "(not exported)";
    eq("nextManualTagColor names the colour createTag then picks", (await S.createTag(d, { name: "c" })).color, predicted);
    chk("nextManualTagColor is exported for the pickers", typeof S.nextManualTagColor === "function");
  }
  // 10. The persisted record carries the colour (createTag saves).
  {
    const { S } = boot(src); const d = fixture();
    await S.createTag(d, { name: "a" }); await S.createTag(d, { name: "b" });
    const back = await S.getAll();
    eq("the saved tags carry their distinct colours", ws0(back).tags.map((t) => t.color), PALETTE.slice(0, 2));
  }
  // ---- the GOAL rotation, which must not move ----
  // 11. Manual tags never advance the goal counter.
  {
    const { S } = boot(src); const d = fixture();
    for (const n of ["a", "b", "c"]) await S.createTag(d, { name: n });
    eq("three manual tags leave the goal rotation at its first colour", S.nextAutoTagColor(ws0(d)), PALETTE[0]);
    await S.createGoal(d, { name: "Ship the report" });
    const auto = ws0(d).tags.find((t) => typeof t.autoGeneratedFromGoalId === "string");
    eq("the first goal's tag takes the goal rotation's first colour", auto && auto.color, PALETTE[0]);
    eq("after one goal tag the goal rotation moves to the second colour", S.nextAutoTagColor(ws0(d)), PALETTE[1]);
  }
  // 12. Trashed goal tags still count (the restore rule).
  {
    const { S } = boot(src); const d = fixture([tag("old-goal", PALETTE[0], { autoGeneratedFromGoalId: "g0", deletedAt: 5 })]);
    eq("a trashed goal tag still advances the goal rotation", S.nextAutoTagColor(ws0(d)), PALETTE[1]);
  }
  // 13. createTag with autoGeneratedFromGoalId takes the goal rotation.
  {
    const { S } = boot(src); const d = fixture([tag("x", PALETTE[0]), tag("g1", PALETTE[0], { autoGeneratedFromGoalId: "g1" })]);
    eq("createTag for a goal takes the goal rotation, not the least-used colour", (await S.createTag(d, { name: "g2", autoGeneratedFromGoalId: "g2" })).color, PALETTE[1]);
  }
  // 14. Duplicate names are still refused (the rule next door, unmoved).
  {
    const { S } = boot(src); const d = fixture([tag("deep work", PALETTE[0])]);
    const r = await S.createTag(d, { name: "Deep Work" });
    chk("a duplicate name is still refused", r && r.err === "duplicate", JSON.stringify(r));
  }
  return rows;
}

const SEEDS = [
  ["createTag goes back to the goal rotation for every tag",
   "color = (typeof f.autoGeneratedFromGoalId === \"string\") ? nextAutoTagColor(ws) : nextManualTagColor(ws);",
   "color = nextAutoTagColor(ws);"],
  ["trashed tags keep their colour reserved",
   "if (!t || t.deletedAt || typeof t.color !== \"string\") return;",
   "if (!t || typeof t.color !== \"string\") return;"],
  ["colours compare case-sensitively",
   "var i = TAG_PALETTE.map(function (c) { return c.toLowerCase(); }).indexOf(t.color.toLowerCase());",
   "var i = TAG_PALETTE.indexOf(t.color);"],
  ["ties go to the LAST palette colour",
   "for (var i = 1; i < uses.length; i++) if (uses[i] < uses[best]) best = i;",
   "for (var i = 1; i < uses.length; i++) if (uses[i] <= uses[best]) best = i;"],
  ["the goal rotation stops counting trashed goal tags",
   "      return t && typeof t.autoGeneratedFromGoalId === \"string\";\n    }).length;",
   "      return t && !t.deletedAt && typeof t.autoGeneratedFromGoalId === \"string\";\n    }).length;"],
  ["createTag ignores an explicit colour",
   "    } else {\n      color = f.color;\n    }",
   "    } else {\n      color = nextManualTagColor(ws);\n    }"],
];

const clean = readSubject();
if (args.includes("--boot-check")) {
  try { boot(clean); console.log("BOOT-CHECK OK   check-tag-colors.mjs"); process.exit(0); }
  catch (e) { console.log("BOOT-CHECK DEAD check-tag-colors.mjs — " + e.message); process.exit(1); }
}

console.log("\nTAG COLOURS — manual tags take the least-used palette colour; the goal rotation is unmoved\n");
let rows;
try { rows = await suite(clean); }
catch (e) { console.error("SUBJECT DID NOT LOAD — " + e.message); process.exit(2); }

const ROW_FLOOR = 20;
if (rows.length < ROW_FLOOR) { console.error(`GATE BROKEN — produced ${rows.length} rows, floor is ${ROW_FLOOR}.`); process.exit(2); }

let failed = 0;
for (const r of rows) if (!r.ok) { failed++; console.log(`  FAIL  ${r.name}   << ${r.extra}`); }
console.log(`TAG COLOURS: ${failed === 0 ? "PASS" : "FAIL"} — ${rows.length - failed} passed, ${failed} failed`);
if (!MUTATE) process.exit(failed === 0 ? 0 : 1);
if (failed > 0) { console.error("\nREFUSING TO SCORE SEEDS — the clean run is not green (Q1)."); process.exit(2); }

console.log("\nMUTATION PASS — every seed must turn the suite red\n");
let escaped = 0, broken = 0;
for (const [name, find, repl] of SEEDS) {
  const n = clean.split(find).length - 1;
  if (n !== 1) { broken++; console.log(`  BROKEN SEED  ${name} (anchor matched ${n}x)`); continue; }
  let mrows;
  try { mrows = await suite(clean.split(find).join(repl)); }
  catch (e) { broken++; console.log(`  BROKEN SEED  ${name} (subject did not load: ${e.message})`); continue; }
  const red = mrows.filter((r) => !r.ok);
  if (!red.length) { escaped++; console.log(`  ESCAPED  ${name}`); }
  else console.log(`  killed   ${name}\n           by: ${red[0].name.slice(0, 92)}`);
}
console.log(`\n  ${SEEDS.length - escaped - broken} killed, ${escaped} escaped, ${broken} broken`);
process.exit(escaped === 0 && broken === 0 ? 0 : 1);
